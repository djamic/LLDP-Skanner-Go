let topoSpriteMounted = false;

// Mount shared SVG <symbol> sprite once so both #network and the filter bar can <use> icons
function ensureTopologyIconDefs(svgSel) {
    if (!topoSpriteMounted && typeof document !== 'undefined' && document.body) {
        topoSpriteMounted = true;
        const holder = document.createElement('div');
        holder.id = 'topoIconSpriteHolder';
        holder.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden;pointer-events:none';
        holder.innerHTML = `<svg id="topoIconSprite" aria-hidden="true" width="0" height="0"><defs id="topoSharedDefs">${topoIconSymbolsMarkup}</defs></svg>`;
        document.body.appendChild(holder);
    }
    if (!svgSel || svgSel.select('defs#topoIconDefs').size?.() > 0) return;
    svgSel.append('defs').attr('id', 'topoIconDefs').html(topoIconSymbolsMarkup);
}

// Replace the plain .fc-dot circles in the top Filter Bar with matching SVG device icons
function initFilterBarIcons() {
    ensureTopologyIconDefs(null);
    if (typeof document === 'undefined') return;
    document.querySelectorAll('.filter-cb').forEach(label => {
        const input = label.querySelector && label.querySelector('input[type="checkbox"]');
        const dot = label.querySelector && label.querySelector('.fc-dot');
        if (!input || !dot || dot.dataset.iconified) return;
        const group = input.dataset ? input.dataset.group : '';
        const isPassive = input.id === 'filterPassive';
        const iconKey = isPassive ? 'passive' : (group && groupColors[group] ? group : '');
        if (!iconKey) return;
        const color = isPassive ? '#90A4AE' : uiNodeCanvasColor({ group });
        dot.dataset.iconified = 'true';
        dot.classList.add('fc-icon-wrap');
        dot.style.color = color;
        dot.innerHTML = `<svg class="fc-icon" viewBox="0 0 32 32" aria-hidden="true"><use href="#topo-icon-${iconKey}"></use></svg>`;
    });
}

function uiNodeIconHref(group) {
    return groupColors[group] ? `#topo-icon-${group}` : '#topo-icon-unknown';
}

function uiNodeCanvasColor(d) {
    if (d.unreachable) return '#ff4444';
    if (Object.prototype.hasOwnProperty.call(uiGroupCanvasColors, d.group)) return uiGroupCanvasColors[d.group];
    return groupColors[d.group] || '#9E9E9E';
}

function uiNodeIconSize(group) {
    return Object.prototype.hasOwnProperty.call(uiGroupIconSizes, group) ? uiGroupIconSizes[group] : 36;
}

// Render the network (incremental)
function renderGraph() {
    const container = document.getElementById('network');
    const width = container.clientWidth;
    const height = container.clientHeight;

    const nodes = Array.from(currentNodes.values());
    const links = Array.from(currentLinks.values());

    // Initialize SVG and zoom on first render
    if (!svg || !g) {
        svg = d3.select('#network')
            .attr('width', width)
            .attr('height', height);
        ensureTopologyIconDefs(svg);

        zoom = d3.zoom()
            .scaleExtent([0.1, 4])
            .on('zoom', (event) => {
                g.attr('transform', event.transform);
            });

        svg.call(zoom);
        g = svg.append('g');
    }

    // Initialize or update simulation
    if (!simulation) {
        simulation = d3.forceSimulation(nodes)
            .force('link', d3.forceLink(links)
                .id(d => d.id)
                .distance(150))
            .force('charge', d3.forceManyBody().strength(-400))
            .force('center', d3.forceCenter(width / 2, height / 2))
            .force('collision', d3.forceCollide().radius(40));
    } else {
        // Update simulation with current data
        simulation.nodes(nodes);
        simulation.force('link').links(links);
        simulation.alpha(0.3).restart(); // Gentle restart
    }

    // UPDATE LINKS
    const link = g.selectAll('line.link')
        .data(links, d => `${d.source.id || d.source}-${d.target.id || d.target}`);

    link.exit().remove();

    const linkEnter = link.enter()
        .append('line')
        .attr('class', 'link')
        .attr('stroke', '#3a5a7c')
        .attr('stroke-opacity', 0.7)
        .attr('stroke-width', 2);

    // Helper: check if link is MAC-REF (not LLDP-discovered)
    const isMacRef = d => {
        const label = (d.label || d.sourceLabel || '');
        return label.includes('MAC-REF');
    };
    // A WLAN client's link (kind 'wlan', module_inventory.go): thin, in the
    // clients' colour, with no label at the access point or gateway, where
    // the links of all its clients meet
    const isWLAN = d => d.kind === 'wlan';

    const linkUpdate = linkEnter.merge(link)
        .attr('class', d => {
            if (d.unreachable) return 'link link-unreachable';
            if (isMacRef(d)) return 'link link-macref';
            return 'link';
        })
        .attr('stroke', d => {
            if (d.unreachable) return '#ff4444';
            if (isWLAN(d)) return '#80DEEA';
            if (isMacRef(d)) return '#FF9800';  // orange for MAC-REF
            return '#3a5a7c';
        })
        .attr('stroke-dasharray', d => {
            if (d.unreachable) return '5,5';
            if (isMacRef(d)) return '8,4';  // longer dash for MAC-REF
            return null;
        })
        .attr('stroke-opacity', d => {
            if (d.unreachable) return 0.5;
            if (isMacRef(d)) return 0.6;
            return 0.7;
        })
        .attr('stroke-width', d => isWLAN(d) ? 1 : isMacRef(d) ? 1.5 : 2);

    // UPDATE SOURCE LABELS
    const sourceLinkLabel = g.selectAll('text.source-label')
        .data(links, d => `${d.source.id || d.source}-${d.target.id || d.target}`);

    sourceLinkLabel.exit().remove();

    const sourceLabelEnter = sourceLinkLabel.enter()
        .append('text')
        .attr('class', 'link-label source-label')
        .attr('font-size', '11px')
        .attr('fill', '#2196F3')
        .attr('font-weight', 'bold');

    // Text on enter and update: the backend rewrites traffic labels every 30 s
    const sourceLabelUpdate = sourceLabelEnter.merge(sourceLinkLabel)
        .text(d => (isWLAN(d) ? '' : d.sourceLabel || ''));

    // UPDATE TARGET LABELS
    const targetLinkLabel = g.selectAll('text.target-label')
        .data(links, d => `${d.source.id || d.source}-${d.target.id || d.target}`);

    targetLinkLabel.exit().remove();

    const targetLabelEnter = targetLinkLabel.enter()
        .append('text')
        .attr('class', 'link-label target-label')
        .attr('font-size', '11px')
        .attr('fill', '#F44336')
        .attr('font-weight', 'bold');

    const targetLabelUpdate = targetLabelEnter.merge(targetLinkLabel)
        .text(d => d.targetLabel || '');

    // UPDATE NODES (functional SVG icons grouped in g.node-group with circle.node halo/hit ring)
    const nodeGroup = g.selectAll('g.node-group')
        .data(nodes, d => d.id);

    nodeGroup.exit().remove();

    const nodeGroupEnter = nodeGroup.enter()
        .append('g')
        .attr('class', 'node-group')
        .call(d3.drag()
            .on('start', dragstarted)
            .on('drag', dragged)
            .on('end', dragended))
        .on('click', (event, d) => {
            event.stopPropagation();
            showInfoPanel(d);
        })
        .on('contextmenu', (event, d) => {
            event.preventDefault();
            showContextMenu(event, d);
        });

    nodeGroupEnter.append('circle')
        .attr('class', 'node')
        .attr('r', 25)
        .attr('fill', 'transparent');

    const visualEnter = nodeGroupEnter.append('g')
        .attr('class', 'node-visual');

    visualEnter.append('use')
        .attr('class', 'node-icon');

    const nodeGroupUpdate = nodeGroupEnter.merge(nodeGroup)
        .attr('class', d => {
            let cls = 'node-group';
            if (d.unreachable) cls += ' is-unreachable';
            if (d.haRole === 'passive') cls += ' is-ha-passive';
            return cls;
        });

    // Update halo/hit ring classes for anomaly, HA active/passive, and Tree focus
    nodeGroupUpdate.select('circle.node')
        .attr('class', d => {
            let cls = 'node';
            if (d.unreachable) cls += ' anomaly-unreachable';
            else if (d.anomalies && d.anomalies.includes('loopback')) cls += ' anomaly-loopback';
            else if (d.anomalies && (d.anomalies.includes('shadow_it') || d.anomalies.includes('congestion'))) cls += ' anomaly-shadow';
            if (d.haRole === 'passive') cls += ' ha-passive';
            else if (d.haRole === 'active') cls += ' ha-active';
            return cls;
        });

    // Update functional SVG icon symbol, size, and semantic color
    nodeGroupUpdate.select('use.node-icon')
        .attr('href', d => uiNodeIconHref(d.group))
        .attr('width', d => uiNodeIconSize(d.group))
        .attr('height', d => uiNodeIconSize(d.group))
        .attr('x', d => -uiNodeIconSize(d.group) / 2)
        .attr('y', d => -uiNodeIconSize(d.group) / 2)
        .style('color', d => uiNodeCanvasColor(d));

    // UPDATE NODE LABELS
    const nodeLabel = g.selectAll('text.node-label')
        .data(nodes, d => d.id);

    nodeLabel.exit().remove();

    const nodeLabelEnter = nodeLabel.enter()
        .append('text')
        .attr('class', 'node-label')
        .attr('text-anchor', 'middle')
        .attr('font-size', '12px')
        .attr('font-weight', 'bold')
        .attr('fill', '#333');

    // Multi-line labels on enter and update (rebuilt only when the text changed)
    const nodeLabelUpdate = nodeLabelEnter.merge(nodeLabel)
        .each(function (d) { uiRenderNodeLabel(this, d); });

    // Update positions on tick
    simulation.on('tick', () => {
        linkUpdate
            .attr('x1', d => d.source.x)
            .attr('y1', d => d.source.y)
            .attr('x2', d => d.target.x)
            .attr('y2', d => d.target.y);

        sourceLabelUpdate
            .attr('x', d => d.source.x + (d.target.x - d.source.x) * 0.25)
            .attr('y', d => d.source.y + (d.target.y - d.source.y) * 0.25);

        targetLabelUpdate
            .attr('x', d => d.source.x + (d.target.x - d.source.x) * 0.75)
            .attr('y', d => d.source.y + (d.target.y - d.source.y) * 0.75);

        nodeGroupUpdate
            .attr('transform', d => `translate(${d.x},${d.y})`);

        nodeLabelUpdate
            .attr("transform", d => `translate(${d.x},${d.y})`);
    });
}

// Drag functions
function dragstarted(event, d) {
    if (!event.active) simulation.alphaTarget(0.3).restart();
    d.fx = d.x;
    d.fy = d.y;
}

function dragged(event, d) {
    d.fx = event.x;
    d.fy = event.y;
}

function dragended(event, d) {
    if (!event.active) simulation.alphaTarget(0);
    d.fx = null;
    d.fy = null;
}

// Filter rendered .device-item rows by #deviceSearch (trimmed, case-insensitive)
function filterDeviceListItems() {
    const searchInput = document.getElementById('deviceSearch');
    const query = (searchInput && searchInput.value ? String(searchInput.value) : '').trim().toLowerCase();
    document.querySelectorAll('.device-item').forEach(item => {
        const text = (item.dataset.searchText || item.textContent || '').toLowerCase();
        item.style.display = !query || text.includes(query) ? 'block' : 'none';
    });
}

// Update device list
function updateDeviceList() {
    const deviceList = document.getElementById('deviceList');
    if (!deviceList) return;

    deviceList.innerHTML = '';

    // Include all group-visible devices even when CONNECTED focus mode is active,
    // preferring the live currentNodes instance so d.x / d.y are available.
    const baseNodes = (rawData && Array.isArray(rawData.nodes))
        ? rawData.nodes.filter(uiGroupShown).map(n => currentNodes.get(n.id) || n)
        : Array.from(currentNodes.values());

    const sortedDevices = baseNodes.sort((a, b) => {
        const aName = a.sysName || a.ip || a.id;
        const bName = b.sysName || b.ip || b.id;
        return aName.localeCompare(bName);
    });

    sortedDevices.forEach(device => {
        const item = document.createElement('div');
        item.className = 'device-item';
        item.dataset.deviceId = device.id;
        item.dataset.searchText = [
            device.sysName, device.label, device.hostname, device.ip, device.id,
            device.voip && device.voip.brand, device.voip && device.voip.model, device.voip && device.voip.firmware
        ]
            .filter(Boolean)
            .join(' ')
            .toLowerCase();

        const name = document.createElement('div');
        name.className = 'device-name';
        name.textContent = device.sysName || device.id;

        const ip = document.createElement('div');
        ip.className = 'device-ip';
        ip.textContent = device.ip || device.id;

        item.appendChild(name);
        item.appendChild(ip);

        item.addEventListener('click', () => {
            if (typeof treeState !== 'undefined' && treeState.tab === 'tree') return;
            let target = currentNodes.get(device.id) || device;
            if (!currentNodes.has(device.id) && filterState.mode === 'CONNECTED' && rawData) {
                filterState.mode = 'ALL';
                filterState.selectedNodeId = null;
                updateTopology(rawData);
                target = currentNodes.get(device.id) || device;
            }
            panToDevice(target);
        });

        deviceList.appendChild(item);
    });

    // Setup search listener once, and always re-apply active query after rebuild
    const searchInput = document.getElementById('deviceSearch');
    if (searchInput && !searchInput.dataset.initialized) {
        searchInput.dataset.initialized = 'true';
        searchInput.addEventListener('input', () => {
            filterDeviceListItems();
        });
    }
    filterDeviceListItems();
}

// Pan to device
function panToDevice(device) {
    if (device.x === undefined || device.y === undefined || !svg || !zoom) return;

    const container = document.getElementById('network');
    const width = container.clientWidth;
    const height = container.clientHeight;

    const scale = 2.0;
    const x = width / 2 - device.x * scale;
    const y = height / 2 - device.y * scale;

    svg.transition()
        .duration(750)
        .call(zoom.transform, d3.zoomIdentity.translate(x, y).scale(scale));

    if (g) {
        g.selectAll('circle.node')
            .filter(d => d && d.id === device.id)
            .attr('stroke', '#ffffff')
            .attr('stroke-width', 4)
            .transition()
            .duration(2500)
            .attr('stroke', null)
            .attr('stroke-width', null);
    }
}

// Update statistics
function updateStats(data) {
    document.getElementById('nodeCount').textContent = `Nodes: ${data.nodes.length}`;
    document.getElementById('linkCount').textContent = `Links: ${data.links.length}`;

    // Update filter counters
    updateFilterCounts(data);

    // E.1: Update Health Score widget
    if (data.health_score !== undefined) {
        updateHealthWidget(data.health_score);
    }

    // E.5: Update Status Bar
    updateStatusBar(data);
}

// Update device type counters in filter bar
function updateFilterCounts(data) {
    const counts = {};
    (data.nodes || []).forEach(n => {
        const g = n.group || 'unknown';
        counts[g] = (counts[g] || 0) + 1;
    });
    // every group the backend emits, printer/server/unknown included
    Object.keys(groupColors).forEach(g => {
        const el = document.getElementById('fc-' + g);
        if (el) el.textContent = counts[g] || 0;
    });
    const passiveEl = document.getElementById('fc-passive');
    if (passiveEl) {
        passiveEl.textContent = (data.nodes || []).filter(n => n.haRole === 'passive').length;
    }
}

// E.1: Health Score Widget update
function updateHealthWidget(score) {
    const scoreEl = document.getElementById('healthScoreVal');
    const barEl   = document.getElementById('healthBarFill');
    const sbEl    = document.getElementById('sbHealth');
    if (!scoreEl) return;

    const val = Math.max(0, Math.min(100, Math.round(score)));
    scoreEl.textContent = val;
    if (sbEl) sbEl.textContent = val + '/100';

    // Color class
    scoreEl.className = 'health-score';
    if (val >= 90)      scoreEl.classList.add('good');
    else if (val >= 70) scoreEl.classList.add('warning');
    else                scoreEl.classList.add('danger');

    // Progress bar: position maps score 0→100 to left edge→right edge
    if (barEl) {
        barEl.style.width = val + '%';
        // Slide gradient: low score = red (right side), high = green (left side)
        // background-position 100%=red, 0%=green
        const bgPos = (100 - val) + '% 0';
        barEl.style.backgroundPosition = bgPos;
    }

    // Update sb-health color
    const sbSpan = document.querySelector('.sb-health span');
    if (sbSpan) {
        sbSpan.style.color = val >= 90 ? '#4CAF50' : val >= 70 ? '#FF9800' : '#F44336';
    }
}

// E.5: Status Bar update
function updateStatusBar(data) {
    const sbSwitches  = document.getElementById('sbSwitches');
    const sbMACs      = document.getElementById('sbMACs');
    const sbAnomalies = document.getElementById('sbAnomalies');
    const sbLastScan  = document.getElementById('sbLastScan');

    if (sbSwitches) {
        const switchCount = (data.nodes || []).filter(n => n.group === 'switch' || n.group === 'router').length;
        sbSwitches.textContent = switchCount;
    }
    if (sbMACs) {
        sbMACs.textContent = data.total_macs !== undefined ? data.total_macs : (data.nodes || []).length;
    }
    if (sbAnomalies) {
        const anomalyCount = (data.nodes || []).filter(n => n.anomalies && n.anomalies.length > 0).length;
        sbAnomalies.textContent = anomalyCount;
        // Color: red if any anomalies
        const sbAnomalyEl = document.querySelector('.sb-anomaly span');
        if (sbAnomalyEl) sbAnomalyEl.style.color = anomalyCount > 0 ? '#F44336' : '#4CAF50';
    }
    if (sbLastScan) {
        sbLastScan.textContent = new Date().toLocaleTimeString();
    }
}

